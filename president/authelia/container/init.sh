#!/bin/sh

# Renders configuration.yml and users_database.yml into APP_ROOT/authelia/config
# on every `docker compose up -d`. The admin password comes from
# AUTHELIA_ADMIN_PASSWORD in president/.env and is hashed here, so the repo never
# holds a password or a hash.

set -eu

conf_path=/config
template_path=/config.template.yml

: "${DOMAINNAME:?}"
: "${AUTHELIA_ADMIN_PASSWORD:?}"

admin_user="${AUTHELIA_ADMIN_USER:-admin}"
admin_email="${AUTHELIA_ADMIN_EMAIL:-admin@$DOMAINNAME}"

umask 077
mkdir -p "$conf_path"

# the template only uses "${VAR}" placeholders, nothing else needs escaping
(
    echo "cat <<EOF"
    cat "$template_path"
    echo EOF
) | sh >"$conf_path/configuration.yml"

hash=$(authelia crypto hash generate argon2 --password "$AUTHELIA_ADMIN_PASSWORD" |
    sed -n 's/^Digest: //p')

if [ -z "$hash" ]; then
    echo "could not hash AUTHELIA_ADMIN_PASSWORD" >&2
    exit 1
fi

# unquoted heredoc on purpose: "$hash" is expanded once, the '$' characters that
# are part of the argon2 digest are written literally
cat >"$conf_path/users_database.yml" <<EOF
---
###############################################################
# generated by president/authelia/container/init.sh
# the password is AUTHELIA_ADMIN_PASSWORD from president/.env
# do not edit: change the env var and re-run the sidecar instead
###############################################################
users:
    ${admin_user}:
        displayname: 'Admin'
        password: '${hash}'
        email: '${admin_email}'
        groups:
            - 'admins'
EOF

chmod 600 "$conf_path/configuration.yml" "$conf_path/users_database.yml"
